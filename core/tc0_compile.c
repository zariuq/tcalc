/* tc0_compile: specializes tc0 to the Micromath theory.  It runs mm_init, reads the compiled rules,
   and writes micromath_gen.h with two routes for every entry point of the theory:
   - mm_arena_*: the keep rules with their matching unrolled, over tc0's own slots;
   - mm_gen_*:   the whole theory over a table of plain number tuples (one constructor), where a
                 symbol is its number: the theory specialized away from the kernel.
   The generated code is trusted to be a faithful specialization; the differential test checks it. */
#include <inttypes.h>
#include <stdio.h>
#include "tc0.c"
#include "micromath.c"

static uint64_t num(Term t) { return N[t].id; }        /* a constant atom as a number */
static void term_expr(FILE *f, Term t) {               /* a constant atom as a tc0 call */
  fprintf(f, N[t].kind == TC0_K_GEN ? "tc0_gen(%" PRIu64 "ull)" : "tc0_code(%" PRIu64 "ull)", N[t].id);
}

int main(void) {
  if (!mm_init()) { fprintf(stderr, "theory init failed\n"); return 1; }
  int ar = con_arity[EQ];
  if (ncon != 1) { fprintf(stderr, "the number route takes a theory of one constructor\n"); return 1; }
  FILE *f = fopen("micromath_gen.h", "w");
  if (!f) { perror("micromath_gen.h"); return 1; }
  fprintf(f, "/* Generated by tc0_compile from the compiled Micromath rules. Do not edit. */\n#pragma once\n"
             "#include <stdlib.h>\n#include <string.h>\n#include \"tc0.h\"\n#include \"micromath.h\"\n\n");

  /* The keep rules over tc0's slots. */
  for (int e = 0; e < 6; e++) {
    const MmEntry *en = &mm_entries[e];
    if (en->kind != MM_ENT_KEEPS) continue;
    const Rule0 *k = &R[en->rule];
    fprintf(f, "static inline bool mm_arena_%s(", en->name);
    for (int i = 0; i < k->nkeep; i++) fprintf(f, "uint64_t p%d, ", i);
    fprintf(f, "uint64_t d) {\n  int c[%d];\n", k->nkeep);
    for (int i = 0; i < k->nkeep; i++)
      fprintf(f, "  const Term *a%d = tc0_args(tc0_slot(p%d), &c[%d], NULL);\n", i, i, i);
    fprintf(f, "  if (");
    for (int i = 0; i < k->nkeep; i++) fprintf(f, "%s!a%d || c[%d] != %u", i ? " || " : "", i, i, k->kcon[i]);
    fprintf(f, ") return false;\n");
    for (int g = 0; g < k->ng; g++) {
      const Guard *q = &k->g[g];
      fprintf(f, "  if (a%u[%u] != ", q->i, q->j);
      if (q->c) term_expr(f, q->c); else fprintf(f, "a%u[%u]", q->i0, q->j0);
      fprintf(f, ") return false;\n");
    }
    fprintf(f, "  Term b[%d] = { ", k->mar);
    for (int j = 0; j < k->mar; j++) {
      if (j) fprintf(f, ", ");
      int h = k->mh[j];
      if (h >= 0) fprintf(f, "a%d[%d]", k->bi[h], k->bj[h]); else term_expr(f, k->mc[j]);
    }
    fprintf(f, " };\n  return tc0_put(d, tc0_app(%u, b));\n}\n\n", k->mcon);
  }

  /* The whole theory over number tuples. */
  const Term *dfl = &P[N[dflt].args];
  fprintf(f, "typedef struct { uint64_t a[%d]; } MmTuple;\nstatic MmTuple *g_slot;\nstatic uint64_t g_nslot, g_last;\n", ar);
  fprintf(f, "static inline const MmTuple *g_at(uint64_t s) {\n  static const MmTuple dflt = { { ");
  for (int j = 0; j < ar; j++) fprintf(f, "%s%" PRIu64 "ull", j ? ", " : "", num(dfl[j]));
  fprintf(f, " } };\n  return s < g_nslot ? &g_slot[s] : &dflt;\n}\n");
  fprintf(f, "static inline bool g_put(uint64_t s, MmTuple t) {\n  if (s >= %uull) return false;\n"
             "  if (s >= g_nslot) {\n    uint64_t m = g_nslot ? g_nslot : 1024; while (m <= s) m *= 2;\n"
             "    MmTuple *p = realloc(g_slot, m * sizeof *p); if (!p) return false;\n"
             "    for (uint64_t i = g_nslot; i < m; i++) p[i] = *g_at(UINT64_MAX);\n"
             "    g_slot = p; g_nslot = m;\n  }\n  g_slot[s] = t; return true;\n}\n", (unsigned)MAX_SLOT);
  fprintf(f, "static inline bool mm_gen_init(void) { free(g_slot); g_slot = NULL; g_nslot = 0; g_last = %" PRIu64 "ull; return true; }\n", last_gen);
  fprintf(f, "static inline uint64_t mm_gen_new_opaque(void) { return g_last == UINT64_MAX ? 0 : ++g_last; }\n");
  fprintf(f, "static inline bool mm_gen_set(uint64_t o, uint64_t f, uint64_t x, uint64_t y, uint64_t s) { return g_put(s, (MmTuple){ { o, f, x, y } }); }\n");
  fprintf(f, "static inline MmBody mm_gen_get(uint64_t s) { const MmTuple *t = g_at(s); return (MmBody){ t->a[0], t->a[1], t->a[2], t->a[3] }; }\n\n");
  for (int e = 0; e < 6; e++) {
    const MmEntry *en = &mm_entries[e];
    const Rule0 *k = &R[en->rule];
    bool fresh = k->fresh >= 0;
    fprintf(f, "static inline %s mm_gen_%s(", fresh ? "uint64_t" : "bool", en->name);
    if (en->kind == MM_ENT_KEEPS) for (int i = 0; i < k->nkeep; i++) fprintf(f, "uint64_t p%d, ", i);
    else for (int i = 0; i < en->nholes; i++) fprintf(f, "uint64_t h%u, ", en->holes[i]);
    fprintf(f, "uint64_t d) {\n");
    for (int i = 0; i < k->nkeep; i++) fprintf(f, "  const uint64_t *a%d = g_at(p%d)->a;\n", i, i);
    for (int g = 0; g < k->ng; g++) {
      const Guard *q = &k->g[g];
      fprintf(f, "  if (a%u[%u] != ", q->i, q->j);
      if (q->c) fprintf(f, "%" PRIu64 "ull", num(q->c)); else fprintf(f, "a%u[%u]", q->i0, q->j0);
      fprintf(f, ") return 0;\n");
    }
    for (int i = 0; i < en->nholes; i++)
      if (k->kind[en->holes[i]] == TC0_GEN_ONLY) fprintf(f, "  if (h%u > g_last) return 0;\n", en->holes[i]);
    if (fresh) fprintf(f, "  if (d >= %uull || g_last == UINT64_MAX) return 0;\n  uint64_t h%d = g_last + 1;\n", (unsigned)MAX_SLOT, k->fresh);
    fprintf(f, "  if (!g_put(d, (MmTuple){ { ");
    for (int j = 0; j < k->mar; j++) {
      if (j) fprintf(f, ", ");
      int h = k->mh[j];
      if (h < 0) fprintf(f, "%" PRIu64 "ull", num(k->mc[j]));
      else if (k->bi[h] >= 0) fprintf(f, "a%d[%d]", k->bi[h], k->bj[h]);
      else fprintf(f, "h%d", h);
    }
    fprintf(f, " } })) return 0;\n");
    if (fresh) fprintf(f, "  return g_last = h%d;\n}\n", k->fresh); else fprintf(f, "  return 1;\n}\n");
  }
  fclose(f);
  return 0;
}
