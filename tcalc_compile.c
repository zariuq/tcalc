/* tcalc_compile: Build-time Second Futamura Specializer for tcalc theories.
   Runs a theory's initialization (here mm_init) to populate tcalc's C[] and R[]
   tables, then inspects the compiled RuleK bytecode/guard structures R[0..nr-1]
   and emits specialized C functions (both Level 2a unrolled arena functions and
   Level 2b schema-specialized flat-tuple functions) with all arities, Wtag
   checks, guard coordinates, fresh-name bounds, and conclusion projections
   unrolled as compile-time constants. */
#include <inttypes.h>
#include <stdio.h>
#include "tcalc.c"
#include "micromath_tcalc.c"

static bool emit_arg_expr(FILE *f, Term a, int fresh_hole) {
  if (N[a].kind == K_NAME) { fprintf(f, "%" PRIu64 "ull", tc_name_id(a)); return true; }
  if (N[a].kind == K_VAR && (int)N[a].head == fresh_hole) { fprintf(f, "f_id"); return true; }
  if (N[a].kind == K_VAR) { fprintf(f, "in[%u]", N[a].head); return true; }
  return false;
}

static bool schema_eligible(int *max_ar) {
  if (ncon < 1) return false;
  int mr = 1;
  for (int c = 0; c < ncon; c++) {
    if (C[c].isdef || C[c].abound || C[c].arity > TC_ARGS) return false;
    if (C[c].arity > mr) mr = C[c].arity;
  }
  for (int rid = 0; rid < nr; rid++) {
    const RuleK *k = &R[rid];
    const Rule *r = RULE(k);
    if (k->flat) {
      const Flat *fl = &FL[k->fl];
      for (int c = 0; c < fl->nconst; c++) if (N[fl->mc[c]].kind != K_NAME) return false;
      continue;
    }
    if (r->nkeep || r->ntake || r->nabsent || r->ncount || r->ntell || r->nneq || k->bounds) return false;
    Term m = r->make.t;
    if (N[m].kind != K_APP || N[m].head >= (uint32_t)ncon || r->make.space != 0) return false;
    for (int j = 0; j < N[m].arity; j++) {
      Term a = argv(m)[j];
      if (N[a].kind != K_NAME && N[a].kind != K_VAR) return false;
    }
  }
  *max_ar = mr;
  return true;
}

int main(void) {
  int ar = 0;
  if (!mm_init()) { fprintf(stderr, "theory init failed\n"); return 1; }
  if (!schema_eligible(&ar)) { fprintf(stderr, "theory outside schema-specializer fragment\n"); return 1; }
  char gen_h[128];
  size_t hlen = strlen(tc_theory.header);
  snprintf(gen_h, sizeof gen_h, "%.*s_gen.h", (int)(hlen > 2 ? hlen - 2 : hlen), tc_theory.header);
  FILE *f = fopen(gen_h, "w");
  if (!f) { perror(gen_h); return 1; }

  fprintf(f, "/* AUTO-GENERATED by tcalc_compile from tcalc RuleK tables R[0..%d]. DO NOT EDIT. */\n", nr - 1);
  fprintf(f, "#pragma once\n#include \"tcalc.h\"\n#include \"%s\"\n#include <stdlib.h>\n#include <string.h>\n\n", tc_theory.header);

  /* 1. Level 2a: Unrolled RuleK over Generic tcalc Arena */
  for (int rid = 0; rid < nr; rid++) {
    const RuleK *k = &R[rid];
    const Rule *r = RULE(k);
    if (!k->flat) continue;
    const Flat *fl = &FL[k->fl];
    fprintf(f, "static inline Occ tc_fire_arena_%d(const Occ *keep, Occ dest) {\n", rid);
    for (int i = 0; i < r->nkeep; i++)
      fprintf(f, "  const Term *a%d = tc_flat_args(keep[%d], %uu);\n", i, i, fl->ktag[i]);
    fprintf(f, "  if (");
    for (int i = 0; i < r->nkeep; i++) fprintf(f, "%s!a%d", i ? " || " : "", i);
    fprintf(f, ") return tc_fire(%d, NULL, keep, NULL);\n", rid);
    if (fl->nguard > 0) {
      fprintf(f, "  if (");
      for (int g = 0; g < fl->nguard; g++) {
        Guard q = fl->guard[g];
        if (q.i0 == r->nkeep) fprintf(f, "%sa%u[%u] != %uu", g ? " || " : "", q.i, q.j, fl->mc[q.j0]);
        else fprintf(f, "%sa%u[%u] != a%u[%u]", g ? " || " : "", q.i, q.j, q.i0, q.j0);
      }
      fprintf(f, ") return 0;\n");
    }
    fprintf(f, "  Term b[%u] = { ", fl->mar ? fl->mar : 1u);
    for (int j = 0; j < fl->mar; j++) {
      if (fl->mi[j] == r->nkeep) fprintf(f, "%s%uu", j ? ", " : "", fl->mc[fl->mj[j]]);
      else fprintf(f, "%sa%u[%u]", j ? ", " : "", fl->mi[j], fl->mj[j]);
    }
    fprintf(f, " };\n  return tc_flat_out(dest, %u, %u, b);\n}\n\n", r->make.space, fl->mhead);
  }

  /* 2. Level 2b: Schema-Specialized Flat-Tuple Engine emitted from R[0..nr-1] */
  bool multi_con = ncon > 1;
  uint64_t unset_in[TC_VARS] = { 0 }, unset_tup[TC_ARGS] = { 0 };
  for (int i = 0; i < tc_theory.unset_nbinds; i++)
    unset_in[tc_theory.unset_hole[i]] = tc_theory.unset_val[i];
  Term um = RULE(&R[tc_theory.unset_rule])->make.t;
  for (int j = 0; j < N[um].arity; j++) {
    Term a = argv(um)[j];
    unset_tup[j] = (N[a].kind == K_NAME) ? tc_name_id(a) : unset_in[N[a].head];
  }
  if (multi_con) fprintf(f, "typedef struct { uint32_t head; uint64_t a[%d]; } TcGenTuple;\n", ar);
  else fprintf(f, "typedef struct { uint64_t a[%d]; } TcGenTuple;\n", ar);
  fprintf(f, "static TcGenTuple *g_slot;\nstatic uint64_t g_nslot, g_last_name;\n\n");
  fprintf(f, "static inline const TcGenTuple *g_at(uint64_t s) {\n  static const TcGenTuple zero = { ");
  if (multi_con) fprintf(f, "%uu, ", N[um].head);
  fprintf(f, "{ ");
  for (int j = 0; j < ar; j++) fprintf(f, "%s%" PRIu64 "ull", j ? ", " : "", unset_tup[j]);
  fprintf(f, " } };\n  return s < g_nslot ? &g_slot[s] : &zero;\n}\n");
  fprintf(f, "static inline bool g_put(uint64_t s, TcGenTuple t) {\n"
             "  if (s >= %" PRIu64 "ull) return false;\n"
             "  if (s >= g_nslot) {\n"
             "    uint64_t m = g_nslot ? g_nslot : 1024; while (m <= s) m *= 2;\n"
             "    TcGenTuple *p = realloc(g_slot, m * sizeof *p); if (!p) return false;\n"
             "    memset(p + g_nslot, 0, (m - g_nslot) * sizeof *p);\n"
             "    g_slot = p; g_nslot = m;\n  }\n"
             "  g_slot[s] = t; return true;\n}\n\n", tc_theory.max_slot);
  fprintf(f, "static inline bool %s_gen_init(void) {\n"
             "  free(g_slot); g_slot = NULL; g_nslot = 0; g_last_name = %" PRIu64 "ull;\n"
             "  return g_put(0, *g_at(0));\n}\n", tc_theory.prefix, next_name - 1);
  fprintf(f, "static inline uint64_t %s_gen_new_opaque(void) {\n"
             "  return g_last_name == UINT64_MAX ? 0 : ++g_last_name;\n}\n", tc_theory.prefix);
  fprintf(f, "static inline bool %s_gen_set(", tc_theory.prefix);
  for (int j = 0; j < C[0].arity; j++) fprintf(f, "uint64_t f%d, ", j);
  fprintf(f, "uint64_t s) {\n  if (");
  for (int j = 0; j < C[0].arity; j++) fprintf(f, "%sf%d > g_last_name", j ? " || " : "", j);
  fprintf(f, ") return false;\n  return g_put(s, (TcGenTuple){ ");
  if (multi_con) fprintf(f, "0u, ");
  fprintf(f, "{ ");
  for (int j = 0; j < C[0].arity; j++) fprintf(f, "%sf%d", j ? ", " : "", j);
  fprintf(f, " } });\n}\n");
  fprintf(f, "static inline %s %s_gen_get(uint64_t s) {\n"
             "  const TcGenTuple *t = g_at(s);\n  return (%s){ ",
          tc_theory.body_type, tc_theory.prefix, tc_theory.body_type);
  for (int j = 0; j < C[0].arity; j++) fprintf(f, "%st->a[%d]", j ? ", " : "", j);
  fprintf(f, " };\n}\n\n");

  for (int rid = 0; rid < nr; rid++) {
    const RuleK *k = &R[rid];
    const Rule *r = RULE(k);
    if (k->flat) {
      const Flat *fl = &FL[k->fl];
      fprintf(f, "static inline bool tc_gen_flat_%d(const uint64_t *keep, uint64_t dest) {\n", rid);
      for (int i = 0; i < r->nkeep; i++) {
        if (multi_con)
          fprintf(f, "  const TcGenTuple *t%d = g_at(keep[%d]); const uint64_t *a%d = t%d->a;\n", i, i, i, i);
        else
          fprintf(f, "  const uint64_t *a%d = g_at(keep[%d])->a;\n", i, i);
      }
      if (multi_con && r->nkeep > 0) {
        fprintf(f, "  if (");
        for (int i = 0; i < r->nkeep; i++)
          fprintf(f, "%st%d->head != %uu", i ? " || " : "", i, fl->ktag[i] >> 9);
        fprintf(f, ") return false;\n");
      }
      if (fl->nguard > 0) {
        fprintf(f, "  if (");
        for (int g = 0; g < fl->nguard; g++) {
          Guard q = fl->guard[g];
          if (q.i0 == r->nkeep)
            fprintf(f, "%sa%u[%u] != %" PRIu64 "ull", g ? " || " : "", q.i, q.j, tc_name_id(fl->mc[q.j0]));
          else
            fprintf(f, "%sa%u[%u] != a%u[%u]", g ? " || " : "", q.i, q.j, q.i0, q.j0);
        }
        fprintf(f, ") return false;\n");
      }
      fprintf(f, "  return g_put(dest, (TcGenTuple){ ");
      if (multi_con) fprintf(f, "%uu, ", fl->mhead);
      fprintf(f, "{ ");
      for (int j = 0; j < fl->mar; j++) {
        if (fl->mi[j] == r->nkeep)
          fprintf(f, "%s%" PRIu64 "ull", j ? ", " : "", tc_name_id(fl->mc[fl->mj[j]]));
        else
          fprintf(f, "%sa%u[%u]", j ? ", " : "", fl->mi[j], fl->mj[j]);
      }
      fprintf(f, " } });\n}\n\n");
    } else if (r->nkeep == 0 && N[r->make.t].kind == K_APP) {
      Term m = r->make.t;
      uint64_t hmask_used = N[m].vm;
      if (r->fresh >= 0) hmask_used &= ~(1ull << r->fresh);
      fprintf(f, "static inline uint64_t tc_gen_axiom_%d(const uint64_t *in, uint64_t dest) {\n", rid);
      if (r->fresh >= 0) fprintf(f, "  if (dest >= %" PRIu64 "ull) return 0;\n", tc_theory.max_slot);
      if (r->fresh >= 0 && hmask_used) {
        fprintf(f, "  if (");
        bool first = true;
        for (int h = 0; h < k->n; h++)
          if (hmask_used >> h & 1) {
            fprintf(f, "%sin[%d] > g_last_name", first ? "" : " || ", h);
            first = false;
          }
        fprintf(f, ") return 0;\n");
      }
      if (r->fresh >= 0)
        fprintf(f, "  if (g_last_name == UINT64_MAX) return 0;\n  uint64_t f_id = g_last_name + 1;\n");
      fprintf(f, "  if (!g_put(dest, (TcGenTuple){ ");
      if (multi_con) fprintf(f, "%uu, ", N[m].head);
      fprintf(f, "{ ");
      for (int j = 0; j < N[m].arity; j++) {
        if (j) fprintf(f, ", ");
        if (!emit_arg_expr(f, argv(m)[j], r->fresh)) { fclose(f); remove(gen_h); return 1; }
      }
      fprintf(f, " } })) return 0;\n");
      if (r->fresh >= 0) fprintf(f, "  g_last_name = f_id;\n  return f_id;\n}\n\n");
      else fprintf(f, "  return 1;\n}\n\n");
    }
  }

  for (int i = 0; i < tc_theory.nentries; i++) {
    const TcEntry *e = &tc_theory.entries[i];
    const RuleK *k = &R[e->rule];
    if (e->kind == TC_ENT_KEEPS) {
      int nk = RULE(k)->nkeep;
      fprintf(f, "static inline bool %s_gen_%s(", tc_theory.prefix, e->name);
      for (int j = 0; j < nk; j++) fprintf(f, "uint64_t p%d, ", j);
      fprintf(f, "uint64_t d) { uint64_t p[%d] = { ", nk);
      for (int j = 0; j < nk; j++) fprintf(f, "%sp%d", j ? ", " : "", j);
      fprintf(f, " }; return tc_gen_flat_%d(p, d); }\n", e->rule);
    } else {
      const char *ret_t = (e->kind == TC_ENT_FRESH) ? "uint64_t" : "bool";
      fprintf(f, "static inline %s %s_gen_%s(", ret_t, tc_theory.prefix, e->name);
      for (int j = 0; j < e->nholes; j++) fprintf(f, "uint64_t h%d, ", j);
      fprintf(f, "uint64_t s) { uint64_t in[%d] = { ", k->n);
      for (int j = 0; j < e->nholes; j++) fprintf(f, "%s[%u] = h%d", j ? ", " : "", e->holes[j], j);
      fprintf(f, " }; return tc_gen_axiom_%d(in, s)%s; }\n",
              e->rule, (e->kind == TC_ENT_FRESH) ? "" : " != 0");
    }
  }

  fclose(f);
  return 0;
}
