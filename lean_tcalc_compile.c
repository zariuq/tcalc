/* lean_tcalc_compile.c: Build-time Second Futamura Specializer for lean_tcalc.
 *
 * Runs lean_tc_init_kernel() to populate tcalc's C[], R[], and FL[] tables,
 * verifies that every rule in R[0..nr-1] belongs to the pure mflat/flat-ordinary
 * fragment, and emits `lean_tcalc_gen.h` containing:
 *   1. Level 2a: Unrolled RuleK arena functions (`tc_lean_fire_arena_<rid>`)
 *      operating over the tcalc occurrence store with all Wtag checks and
 *      FL[k->fl] guard coordinates unrolled as compile-time constants.
 *   2. Level 2b: Schema-specialized flat-tuple functions (`tc_lean_gen_axiom_<rid>`
 *      and `tc_lean_gen_flat_<rid>`) operating over 32-byte `TcLeanGenTuple`
 *      slots (`{ uint32_t tag; uint32_t pad; uint64_t a[3]; }`) with all space
 *      tags, constructor heads, constant guards (`T_ID_ZERO` -> `0ull`), and
 *      cross-premise equality guards unrolled as compile-time constants.
 */
#include <inttypes.h>
#include <stdio.h>
#include "tcalc.c"
#include "lean_tcalc_theory.h"

static bool lean_schema_eligible(int *max_ar) {
    if (ncon < 1 || nr < 1) return false;
    int mr = 1;
    for (int c = 0; c < ncon; c++) {
        if (C[c].isdef || C[c].abound || C[c].arity > TC_ARGS) return false;
        if (C[c].arity > mr) mr = C[c].arity;
    }
    for (int rid = 0; rid < nr; rid++) {
        const RuleK *k = &R[rid];
        const Rule *r = RULE(k);
        if (k->flat) {
            const Flat *fl = &FL[k->fl];
            if (!fl->ordinary) return false;
            for (int c = 0; c < fl->nconst; c++) {
                if (fl->mc[c] != T_ID_ZERO && N[fl->mc[c]].kind != K_NAME) return false;
            }
            continue;
        }
        if (!k->mflat || r->nkeep || r->ntake || r->nabsent || r->ncount || r->ntell || r->nneq || k->bounds) {
            return false;
        }
        Term m = r->make.t;
        if (N[m].kind != K_APP || N[m].head >= (uint32_t)ncon) return false;
        for (int j = 0; j < N[m].arity; j++) {
            Term a = argv(m)[j];
            if (a != T_ID_ZERO && N[a].kind != K_NAME && N[a].kind != K_VAR) return false;
        }
    }
    *max_ar = mr;
    return true;
}

static uint64_t const_term_to_u64(Term t) {
    if (t == T_ID_ZERO) return 0ull;
    return tc_name_id(t);
}

int main(void) {
    int ar = 0;
    lean_tc_init_kernel();
    if (!lean_schema_eligible(&ar)) {
        fprintf(stderr, "lean_tcalc_compile: theory outside schema-specializer fragment\n");
        return 1;
    }
    FILE *f = fopen("lean_tcalc_gen.h", "w");
    if (!f) {
        perror("lean_tcalc_gen.h");
        return 1;
    }

    fprintf(f, "/* AUTO-GENERATED by lean_tcalc_compile from tcalc RuleK tables R[0..%d] and FL[0..%u]. DO NOT EDIT. */\n",
            nr - 1, nfl ? nfl - 1 : 0u);
    fprintf(f, "#pragma once\n#include \"tcalc.h\"\n#include \"lean_tcalc_theory.h\"\n#include <stdlib.h>\n#include <string.h>\n\n");

    /* 1. Level 2a: Unrolled RuleK over Generic tcalc Arena */
    for (int rid = 0; rid < nr; rid++) {
        const RuleK *k = &R[rid];
        const Rule *r = RULE(k);
        if (!k->flat) continue;
        const Flat *fl = &FL[k->fl];
        fprintf(f, "static inline Occ tc_lean_fire_arena_%d(const Occ *keep, Occ dest) {\n", rid);
        for (int i = 0; i < r->nkeep; i++) {
            fprintf(f, "  const Term *a%d = tc_flat_args(keep[%d], %uu);\n", i, i, fl->ktag[i]);
        }
        fprintf(f, "  if (");
        for (int i = 0; i < r->nkeep; i++) fprintf(f, "%s!a%d", i ? " || " : "", i);
        fprintf(f, ") return 0;\n");
        if (fl->nguard > 0) {
            fprintf(f, "  if (");
            for (int g = 0; g < fl->nguard; g++) {
                Guard q = fl->guard[g];
                if (q.i0 == r->nkeep) {
                    if (fl->mc[q.j0] == T_ID_ZERO) {
                        fprintf(f, "%sa%u[%u] != T_ID_ZERO", g ? " || " : "", q.i, q.j);
                    } else {
                        fprintf(f, "%sa%u[%u] != %uu", g ? " || " : "", q.i, q.j, fl->mc[q.j0]);
                    }
                } else {
                    fprintf(f, "%sa%u[%u] != a%u[%u]", g ? " || " : "", q.i, q.j, q.i0, q.j0);
                }
            }
            fprintf(f, ") return 0;\n");
        }
        fprintf(f, "  return tc_flat_fire(%d, keep, NULL, dest);\n}\n\n", rid);
    }

    fprintf(f, "static inline Occ tc_lean_fire_arena_dispatch(int rule, const Occ *keep, Occ dest) {\n");
    fprintf(f, "  switch (rule) {\n");
    for (int rid = 0; rid < nr; rid++) {
        if (!R[rid].flat) continue;
        fprintf(f, "    case %d: return tc_lean_fire_arena_%d(keep, dest);\n", rid, rid);
    }
    fprintf(f, "    default: return 0;\n  }\n}\n\n");

    /* 2. Level 2b: Schema-Specialized Flat-Tuple Engine emitted from R[0..nr-1] */
    fprintf(f, "typedef struct { uint32_t tag; uint32_t pad; uint64_t a[%d]; } TcLeanGenTuple;\n", ar);
    fprintf(f, "static TcLeanGenTuple *g_lean_slot = NULL;\n");
    fprintf(f, "static uint32_t g_lean_nslot = 0, g_lean_cap = 0;\n\n");

    fprintf(f, "static inline void lean_gen_init(void) {\n");
    fprintf(f, "  free(g_lean_slot);\n");
    fprintf(f, "  g_lean_cap = 65536u;\n");
    fprintf(f, "  g_lean_slot = (TcLeanGenTuple *)calloc(g_lean_cap, sizeof(TcLeanGenTuple));\n");
    fprintf(f, "  g_lean_nslot = 1u;\n");
    fprintf(f, "}\n\n");

    fprintf(f, "static inline void lean_gen_free(void) {\n");
    fprintf(f, "  free(g_lean_slot);\n");
    fprintf(f, "  g_lean_slot = NULL;\n");
    fprintf(f, "  g_lean_nslot = g_lean_cap = 0;\n");
    fprintf(f, "}\n\n");

    fprintf(f, "static inline const TcLeanGenTuple *lean_gen_at(Occ o) {\n");
    fprintf(f, "  static const TcLeanGenTuple zero = { 0u, 0u, { ");
    for (int j = 0; j < ar; j++) fprintf(f, "%s0ull", j ? ", " : "");
    fprintf(f, " } };\n");
    fprintf(f, "  return (o > 0u && o < g_lean_nslot) ? &g_lean_slot[o] : &zero;\n");
    fprintf(f, "}\n\n");

    fprintf(f, "static inline Occ lean_gen_push(TcLeanGenTuple t) {\n");
    fprintf(f, "  if (__builtin_expect(g_lean_nslot >= g_lean_cap, 0)) {\n");
    fprintf(f, "    uint32_t ncap = g_lean_cap ? g_lean_cap * 2u : 65536u;\n");
    fprintf(f, "    TcLeanGenTuple *p = (TcLeanGenTuple *)realloc(g_lean_slot, (size_t)ncap * sizeof(TcLeanGenTuple));\n");
    fprintf(f, "    if (!p) return 0;\n");
    fprintf(f, "    memset(p + g_lean_cap, 0, (size_t)(ncap - g_lean_cap) * sizeof(TcLeanGenTuple));\n");
    fprintf(f, "    g_lean_slot = p;\n");
    fprintf(f, "    g_lean_cap = ncap;\n");
    fprintf(f, "  }\n");
    fprintf(f, "  Occ o = g_lean_nslot++;\n");
    fprintf(f, "  g_lean_slot[o] = t;\n");
    fprintf(f, "  return o;\n");
    fprintf(f, "}\n\n");

    for (int rid = 0; rid < nr; rid++) {
        const RuleK *k = &R[rid];
        const Rule *r = RULE(k);
        if (k->flat) {
            const Flat *fl = &FL[k->fl];
            uint32_t mtag = (fl->mhead << 9) | ((uint32_t)r->make.space << 1) | 1u;
            fprintf(f, "static inline Occ tc_lean_gen_flat_%d(const Occ *keep) {\n", rid);
            for (int i = 0; i < r->nkeep; i++) {
                fprintf(f, "  const TcLeanGenTuple *t%d = lean_gen_at(keep[%d]);\n", i, i);
            }
            fprintf(f, "  if (");
            for (int i = 0; i < r->nkeep; i++) {
                fprintf(f, "%st%d->tag != %uu", i ? " || " : "", i, fl->ktag[i]);
            }
            fprintf(f, ") return 0;\n");
            for (int i = 0; i < r->nkeep; i++) {
                fprintf(f, "  const uint64_t *a%d = t%d->a;\n", i, i);
            }
            if (fl->nguard > 0) {
                fprintf(f, "  if (");
                for (int g = 0; g < fl->nguard; g++) {
                    Guard q = fl->guard[g];
                    if (q.i0 == r->nkeep) {
                        fprintf(f, "%sa%u[%u] != %" PRIu64 "ull", g ? " || " : "",
                                q.i, q.j, const_term_to_u64(fl->mc[q.j0]));
                    } else {
                        fprintf(f, "%sa%u[%u] != a%u[%u]", g ? " || " : "", q.i, q.j, q.i0, q.j0);
                    }
                }
                fprintf(f, ") return 0;\n");
            }
            fprintf(f, "  return lean_gen_push((TcLeanGenTuple){ %uu, 0u, { ", mtag);
            for (int j = 0; j < ar; j++) {
                if (j > 0) fprintf(f, ", ");
                if (j < (int)fl->mar) {
                    if (fl->mi[j] == r->nkeep) {
                        fprintf(f, "%" PRIu64 "ull", const_term_to_u64(fl->mc[fl->mj[j]]));
                    } else {
                        fprintf(f, "a%u[%u]", fl->mi[j], fl->mj[j]);
                    }
                } else {
                    fprintf(f, "0ull");
                }
            }
            fprintf(f, " } });\n}\n\n");
            continue;
        }
        /* k->mflat leaf emission rule */
        Term m = r->make.t;
        uint32_t mtag = (N[m].head << 9) | ((uint32_t)r->make.space << 1) | 1u;
        fprintf(f, "static inline Occ tc_lean_gen_axiom_%d(const uint64_t *in) {\n", rid);
        fprintf(f, "  return lean_gen_push((TcLeanGenTuple){ %uu, 0u, { ", mtag);
        for (int j = 0; j < ar; j++) {
            if (j > 0) fprintf(f, ", ");
            if (j < N[m].arity) {
                Term a = argv(m)[j];
                if (N[a].kind == K_VAR) fprintf(f, "in[%u]", N[a].head);
                else fprintf(f, "%" PRIu64 "ull", const_term_to_u64(a));
            } else {
                fprintf(f, "0ull");
            }
        }
        fprintf(f, " } });\n}\n\n");
    }

    fprintf(f, "static inline Occ tc_lean_gen_mflat_dispatch(int rule, const uint64_t *in) {\n");
    fprintf(f, "  switch (rule) {\n");
    for (int rid = 0; rid < nr; rid++) {
        if (R[rid].flat) continue;
        fprintf(f, "    case %d: return tc_lean_gen_axiom_%d(in);\n", rid, rid);
    }
    fprintf(f, "    default: return 0;\n  }\n}\n\n");

    fprintf(f, "static inline Occ tc_lean_gen_flat_dispatch(int rule, const Occ *keep) {\n");
    fprintf(f, "  switch (rule) {\n");
    for (int rid = 0; rid < nr; rid++) {
        if (!R[rid].flat) continue;
        fprintf(f, "    case %d: return tc_lean_gen_flat_%d(keep);\n", rid, rid);
    }
    fprintf(f, "    default: return 0;\n  }\n}\n");

    fclose(f);
    return 0;
}
