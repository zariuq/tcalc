(* ========================================================================= *)
(* The premise ledger of a top theorem, generated in a session.             *)
(*                                                                           *)
(* ledger_lines name th: the antecedent conjuncts of th (after its          *)
(* universal quantifiers), each classified as                                *)
(*   discharged  a theorem of the session, given as a candidate, proves it: *)
(*               the theorem's conclusion matches the conjunct (or the      *)
(*               conjunct, instantiated, matches the theorem's conclusion;  *)
(*               the instantiation is shown). A candidate with antecedents  *)
(*               discharges a conjunct given those antecedents, which are  *)
(*               then ledgered in turn, indented;                           *)
(*   obligation  a named obligation of the host (or of the code that runs   *)
(*               the checker), given as a pattern;                          *)
(*   open        neither, or an obligation given as open, with its name.    *)
(* ledger_put_part file n part: LEDGER.txt is a fixed header and numbered  *)
(* parts, each generated by the session that can state its theorems; the   *)
(* call replaces part n (its first line "PART n: ...") and keeps the        *)
(* others. The ledger is never edited by hand.                               *)
(* ========================================================================= *)

(* An obligation is given as (pattern, open, name): open is true for an   *)
(* obligation nobody has proved yet, false for one of the host. A pattern  *)
(* is written as an abstraction over its variables, \x1 .. xn. body, so    *)
(* that its variables are variables in any session (a binder shadows a    *)
(* constant of that name); its body is matched.                            *)

(* The antecedent conjuncts of a theorem's conclusion. *)
let ledger_antecedents tm =
  let _,body = strip_forall tm in
  if is_imp body then conjuncts(lhand body) else [];;

(* A candidate's conclusion and its antecedents (after its own quantifiers). *)
let ledger_parts th =
  let _,body = strip_forall(concl th) in
  if is_imp body then rand body, conjuncts(lhand body) else body, [];;

let ledger_match pat tm = try Some(term_match [] pat tm) with Failure _ -> None;;

(* A candidate discharges c fully when its conclusion's pattern matches c,  *)
(* and at an instance when c's pattern matches the candidate's conclusion.  *)
let ledger_discharge cands c =
  let show_inst inst = String.concat ", "
    (map (fun (t,v) -> string_of_term v ^ " := " ^ string_of_term t) inst) in
  let try_one (n,th) =
    if hyp th <> [] then None else
    match ledger_match (concl th) c with
      Some _ -> Some(n, "", [])
    | None ->
    match ledger_match c (concl th) with
      Some(_,inst,_) -> Some(n, " at " ^ show_inst inst, [])
    | None ->
    let cl,ants = ledger_parts th in
    match ledger_match cl c with
      Some(_,inst,_) -> Some(n, "", map (vsubst inst) ants)
    | None ->
      match ledger_match c cl with
        Some(_,inst,_) ->
          let shown = String.concat ", "
            (map (fun (t,v) -> string_of_term v ^ " := " ^ string_of_term t) inst) in
          Some(n, " at " ^ shown, ants)
      | None -> None in
  let rec first = function [] -> None
    | x::xs -> (match try_one x with Some r -> Some r | None -> first xs) in
  first cands;;

let ledger_pattern pat =
  let vs,body = strip_abs pat in
  let free = subtract (frees body) vs in
  if free <> [] then
    failwith ("ledger: unbound variables in a pattern: " ^
              String.concat " " (map (fst o dest_var) free))
  else body;;

let ledger_obligation obls c =
  let rec first = function [] -> None
    | (pat,kind,name)::xs ->
        (match ledger_match (ledger_pattern pat) c with
           Some _ -> Some(kind,name) | None -> first xs) in
  first obls;;

let ledger_one_line s =
  String.concat " " (List.filter (fun w -> w <> "")
    (String.split_on_char ' '
      (String.map (fun ch -> if ch = '\n' then ' ' else ch) s)));;

let rec ledger_conjunct depth cands obls c =
  let ind = String.make (2 * depth + 2) ' ' in
  let show = ledger_one_line(string_of_term c) in
  match ledger_obligation obls c with
    Some(false,name) -> [ind ^ "obligation " ^ name ^ ": " ^ show]
  | Some(true,name) -> [ind ^ "OPEN " ^ name ^ ": " ^ show]
  | None ->
    match ledger_discharge cands c with
      Some(n,at,ants) ->
        (ind ^ "discharged by " ^ n ^ at ^ ": " ^ show) ::
        (if depth >= 3 then [] else
         List.concat (map (ledger_conjunct (depth + 1) cands obls) ants))
    | None -> [ind ^ "OPEN: " ^ show];;

let ledger_lines cands obls (name,th) =
  ("THEOREM " ^ name ^ " (hypotheses " ^ string_of_int(length(hyp th)) ^ ")") ::
  List.concat (map (ledger_conjunct 0 cands obls) (ledger_antecedents(concl th)));;

let ledger_header =
  ["GENERATED by ledger.ml (ledger_put_part); never edit by hand.";
   "Premises of the top theorems: discharged (by a theorem of the session),";
   "obligation (named, of the host or of the code that runs the checker), or OPEN.";
   "Each part is written by the session that has its theorems."];;

let ledger_read_lines file =
  try let ic = open_in file in
      let acc = ref [] in
      (try while true do acc := input_line ic :: !acc done with End_of_file -> close_in ic);
      rev !acc
  with Sys_error _ -> [];;

let ledger_part_of l =
  if String.length l > 5 && String.sub l 0 5 = "PART " then
    try Some(int_of_string(String.sub l 5 (String.index l ':' - 5))) with _ -> None
  else None;;

(* The parts of a ledger file, each (n, its lines). *)
let ledger_parts_of lines =
  let close cur parts = match cur with None -> parts | Some(k,ls) -> (k,rev ls)::parts in
  let rec go parts cur = function
      [] -> rev (close cur parts)
    | l::ls -> (match ledger_part_of l, cur with
                  Some k, _ -> go (close cur parts) (Some(k,[l])) ls
                | None, Some(k,cl) -> go parts (Some(k,l::cl)) ls
                | None, None -> go parts None ls) in
  go [] None lines;;

let ledger_put_part file n title sections =
  let part = ("PART " ^ string_of_int n ^ ": " ^ title) ::
             List.concat (map (fun ls -> "" :: ls) sections) @ [""] in
  let parts = filter (fun (k,_) -> k <> n) (ledger_parts_of(ledger_read_lines file)) in
  let parts = sort (fun (a,_) (b,_) -> a < b) ((n,part)::parts) in
  let oc = open_out file in
  List.iter (fun l -> output_string oc (l ^ "\n")) (ledger_header @ [""]);
  List.iter (fun (_,ls) -> List.iter (fun l -> output_string oc (l ^ "\n")) ls) parts;
  close_out oc;;
