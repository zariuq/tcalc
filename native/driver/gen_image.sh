#!/bin/bash
# gen_image.sh RECORD.hol SYMBOL: the x86 image proved in a t-ISA image record
# (tisa_image NAME `PROG` "HEX" [...]) as assembler source, bytes for bytes,
# between SYMBOL and SYMBOL_end.
set -euo pipefail
rec=$1 sym=$2
hex=$(grep -o '"[0-9a-f]*"' "$rec" | head -1 | tr -d '"')
[ -n "$hex" ] || { echo "no image bytes in $rec" >&2; exit 2; }
echo "/* Generated by gen_image.sh from $(basename "$rec"); do not edit. */"
echo "        .text"
echo "        .globl  $sym, ${sym}_end"
echo "$sym:"
echo "$hex" | fold -w 32 | sed 's/\(..\)/0x\1, /g; s/, $//; s/^/        .byte   /'
echo "${sym}_end:"
echo '        .section .note.GNU-stack,"",%progbits'
